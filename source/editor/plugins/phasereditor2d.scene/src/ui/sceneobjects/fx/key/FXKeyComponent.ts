/// <reference path="../FXProperty.ts" />
namespace phasereditor2d.scene.ui.sceneobjects {

    export class FXKeyComponent extends Component<FXKey> {

        // In Phaser 4, Key.color is a normalized RGBA array,
        // so the editor stores a hex string and applies it with setColor().
        static color = FXProperty(FXColorProperty("color", "#ffffff", "Color", "phaser:Phaser.Filters.Key.color",
            (fx: Phaser.Filters.Key, hex: string) => fx.setColor(hex)));

        static threshold = FXProperty(SimpleProperty("threshold", 0.0625, "Threshold", "phaser:Phaser.Filters.Key.threshold", false, undefined, 0.01, 0, 1));
        static feather = FXProperty(SimpleProperty("feather", 0, "Feather", "phaser:Phaser.Filters.Key.feather", false, undefined, 0.01, 0, 1));
        static isolate = FXProperty(SimpleProperty("isolate", false, "Isolate", "phaser:Phaser.Filters.Key.isolate"));

        constructor(obj: FXKey) {
            super(obj, [
                FXKeyComponent.color,
                FXKeyComponent.threshold,
                FXKeyComponent.feather,
                FXKeyComponent.isolate
            ]);
        }

        buildSetObjectPropertiesCodeDOM(args: ISetObjectPropertiesCodeDOMArgs): void {

            // All the properties are passed in the addKey() config object
            // generated by the code DOM builder, so no assignments are emitted here.
        }
    }
}
